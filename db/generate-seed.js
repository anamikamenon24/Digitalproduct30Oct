// One-off generator: turns the original mock catalogue into db/seed.sql and writes the private
// sample download files to /storage. Re-run with `node db/generate-seed.js` if the catalogue changes.
import { writeFileSync, mkdirSync } from 'node:fs'
import { products, CATEGORIES } from './catalog.js'

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
const toMb = (size) => {
  const [n, unit] = size.split(' ')
  return unit === 'GB' ? Number(n) * 1024 : Number(n)
}

const FEATURED = new Set(['notion-creator-os', 'motion-design-101', 'golden-hour-presets', 'glyphs-3d-icons'])

const NAMES = ['Priya S.', 'Marcus L.', 'Ava T.', 'Diego R.', 'Hana K.', 'Leo M.', 'Sofia G.', 'Noah B.', 'Mei C.', 'Omar F.', 'Zara P.', 'Ethan W.', 'Lina D.', 'Kofi A.', 'Isla R.', 'Mateo V.']
const COMMENTS = {
  5: [
    'Honestly the best purchase I made this year. Set up in minutes and it looks incredible.',
    'Super polished and the creator clearly cares about the details. Instant download worked perfectly.',
    'Bought it on my phone from an Instagram link and was using it ten minutes later. Love it.',
    'Exactly what I needed for a client project. Saved me a full weekend of work.',
    'Beautifully made and really easy to customise. Already recommended it to two friends.',
  ],
  4: [
    'Great value. I wish there were a couple more variations, but what is there is top quality.',
    'Really solid. Took a little time to learn, but the included guide helped a lot.',
    'Very happy with it overall. A few more examples would make it perfect.',
  ],
  3: ['Good starting point, though I had to tweak quite a bit to fit my style.'],
}

let sql = `-- Generated by db/generate-seed.js. Safe to run repeatedly (upserts, no duplicates).\n\n`

sql += `insert into categories (name, slug) values\n`
sql += CATEGORIES.map((c) => `  (${q(c)}, ${q(slugify(c))})`).join(',\n')
sql += `\non conflict (slug) do update set name = excluded.name;\n\n`

for (const p of products) {
  const cover = { palette: p.palette, motif: p.motif, ...(p.glyph ? { glyph: p.glyph } : {}) }
  sql += `insert into products (category_id, title, slug, short_description, description, price_cents, cover_url, file_path, file_format, file_size_mb, is_featured, created_at, creator, includes, cover_style)
select c.id, ${q(p.title)}, ${q(p.id)}, ${q(p.tagline)}, ${q(p.description)}, ${Math.round(p.price * 100)}, null, ${q(`${p.id}-sample.txt`)}, ${q(p.format)}, ${toMb(p.size)}, ${FEATURED.has(p.id)}, ${q(p.date + 'T10:00:00Z')}, ${q(p.creator)}, ${q(JSON.stringify(p.includes))}::jsonb, ${q(JSON.stringify(cover))}::jsonb
from categories c where c.slug = ${q(slugify(p.category))}
on conflict (slug) do update set
  category_id = excluded.category_id, title = excluded.title, short_description = excluded.short_description,
  description = excluded.description, price_cents = excluded.price_cents, file_path = excluded.file_path,
  file_format = excluded.file_format, file_size_mb = excluded.file_size_mb, is_featured = excluded.is_featured,
  created_at = excluded.created_at, creator = excluded.creator, includes = excluded.includes, cover_style = excluded.cover_style;\n\n`
}

// Seeded reviews have no user account. Replace them on every run; real buyers' reviews are untouched.
sql += `delete from reviews where user_id is null;\n\n`
let n = 0
for (const [i, p] of products.entries()) {
  const count = 3 + (i % 3) // 3, 4 or 5 reviews
  const rows = []
  for (let j = 0; j < count; j++, n++) {
    const rating = p.rating >= 4.8 ? (j === 3 ? 4 : 5) : p.rating >= 4.6 ? (j % 2 ? 4 : 5) : j === 1 ? 3 : j % 2 ? 4 : 5
    const pool = COMMENTS[rating]
    const day = String(1 + ((i * 7 + j * 5) % 27)).padStart(2, '0')
    const month = String(10 - (j % 4)).padStart(2, '0')
    rows.push(`  (${q(NAMES[n % NAMES.length])}, ${rating}, ${q(pool[(i + j) % pool.length])}, ${q(`2026-${month}-${day}T12:00:00Z`)})`)
  }
  sql += `insert into reviews (product_id, user_id, reviewer_name, rating, comment, created_at)
select p.id, null, v.name, v.rating, v.comment, v.created_at::timestamptz
from products p, (values\n${rows.join(',\n')}\n) as v(name, rating, comment, created_at)
where p.slug = ${q(p.id)};\n\n`
}

sql += `insert into discount_codes (code, percent_off, active) values ('WELCOME10', 10, true)
on conflict (code) do update set percent_off = excluded.percent_off, active = excluded.active;
-- An expired code, so the "inactive codes are rejected" rule can be tested.
insert into discount_codes (code, percent_off, active) values ('SUMMER25', 25, false)
on conflict (code) do update set percent_off = excluded.percent_off, active = excluded.active;
`

writeFileSync(new URL('./seed.sql', import.meta.url), sql)

const storage = new URL('../storage/', import.meta.url)
mkdirSync(storage, { recursive: true })
for (const p of products) {
  writeFileSync(
    new URL(`${p.id}-sample.txt`, storage),
    `Pixelora — ${p.title}\nby ${p.creator}\n\n${p.tagline}\n\nWhat's included:\n${p.includes.map((x) => `  • ${x}`).join('\n')}\n\nFormat: ${p.format}\n\nThis is a small sample file for local testing. In production this would be the real product download.\n`,
  )
}

console.log(`Wrote db/seed.sql (${products.length} products, ${n} reviews) and ${products.length} files in /storage`)
